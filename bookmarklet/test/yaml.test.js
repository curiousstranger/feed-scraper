import { test } from 'node:test';
import assert from 'node:assert/strict';
import { toYaml, slugForUrl, githubNewFileUrl, isValidSiteId, MAX_GITHUB_URL_LENGTH } from '../src/yaml.js';

const CFG = {
  id: 'example-blog',
  name: 'Example "Blog"',
  description: 'Unofficial RSS feed scraped from https://example.com/blog',
  listing_url: 'https://example.com/blog',
  base_url: 'https://example.com',
  item_selector: 'div.post-card',
  link_selector: 'a',
  title_selector: 'h2[class*="title"]',
  date_selector: null,
  category_selector: "span[data-kind='tag']",
};

test('toYaml snapshot: key order, quoting, omitted unpicked selectors', () => {
  assert.equal(
    toYaml(CFG, { date: '2026-09-18' }),
    `# Generated by the feed-scraper selector-picker bookmarklet
# from https://example.com/blog on 2026-09-18.

id: example-blog
name: "Example \\"Blog\\""
description: "Unofficial RSS feed scraped from https://example.com/blog"
listing_url: "https://example.com/blog"
base_url: "https://example.com"

item_selector: 'div.post-card'
link_selector: 'a'
title_selector: 'h2[class*="title"]'
category_selector: 'span[data-kind=''tag'']'

fetch_detail: true
max_items: 75

user_agent: "Mozilla/5.0 (compatible; PersonalSiteRSSBot/1.0; run by a single subscriber for personal use)"
`,
  );
});

test('slugForUrl: hostname minus www/TLD plus first path segment', () => {
  assert.equal(slugForUrl('https://www.anthropic.com/news'), 'anthropic-news');
  assert.equal(slugForUrl('https://blog.example.com/'), 'blog-example');
  assert.equal(slugForUrl('https://example.com/Posts_2026/page/2?x=1'), 'example-posts-2026');
});

test('githubNewFileUrl pre-fills path and content', () => {
  const { url, ok } = githubNewFileUrl('curiousstranger/feed-scraper', 'example-blog', 'id: x\n');
  assert.equal(ok, true);
  assert.equal(
    url,
    'https://github.com/curiousstranger/feed-scraper/new/main?filename=sites/example-blog.yaml&value=id%3A%20x%0A',
  );
});

test('githubNewFileUrl is not ok past the length limit', () => {
  const { url, ok } = githubNewFileUrl('o/r', 'x', 'y'.repeat(MAX_GITHUB_URL_LENGTH));
  assert.ok(url.length > MAX_GITHUB_URL_LENGTH);
  assert.equal(ok, false);
});

test('toYaml: YAML keywords and numeric ids are always quoted', () => {
  // IDs that would be parsed as non-strings by PyYAML must be quoted
  const problematicIds = ['123', 'no', 'true', 'null', '2026-09-18'];
  for (const id of problematicIds) {
    const yaml = toYaml({ ...CFG, id }, { date: '2026-09-18' });
    // Check the line starts with `id: "` (i.e., is quoted)
    assert.match(yaml, /^id: ".+"$/m, `id '${id}' should be quoted but got: ${yaml.split('\n')[4]}`);
  }

  // Normal slugs should remain unquoted
  const yaml = toYaml({ ...CFG, id: 'example-blog' }, { date: '2026-09-18' });
  assert.match(yaml, /^id: example-blog$/m, 'example-blog should not be quoted');
});

test('isValidSiteId: lowercase letters, digits and hyphens only, no leading hyphen', () => {
  for (const id of ['example-blog', 'a1', '2026-news', 'x']) assert.equal(isValidSiteId(id), true, id);
  for (const id of ['../evil', 'a/b', 'Evil', '', 'a b', '-a', 'a.b', 'a\n']) {
    assert.equal(isValidSiteId(id), false, JSON.stringify(id));
  }
});

const FEATURED = {
  featured_item_selector: 'article[class*="featured"] a',
  featured_link_selector: null,
  featured_title_selector: 'h2',
  featured_date_selector: null,
  featured_category_selector: "span[data-kind='tag']",
};

test('toYaml: a featured section follows the main selectors; unpicked featured fields omitted', () => {
  const yaml = toYaml({ ...CFG, ...FEATURED }, { date: '2026-10-13' });
  assert.match(
    yaml,
    /^category_selector: 'span\[data-kind=''tag''\]'\n\nfeatured_item_selector: 'article\[class\*="featured"\] a'\nfeatured_title_selector: 'h2'\nfeatured_category_selector: 'span\[data-kind=''tag''\]'\n\nfetch_detail: true$/m,
  );
});

test('toYaml: featured_link_selector sits between the featured item and title', () => {
  const yaml = toYaml({ ...CFG, ...FEATURED, featured_item_selector: 'section.hero', featured_link_selector: 'a' }, { date: '2026-10-13' });
  assert.match(yaml, /^featured_item_selector: 'section\.hero'\nfeatured_link_selector: 'a'\nfeatured_title_selector: 'h2'$/m);
});

test('toYaml: no featured_item_selector → no featured keys at all', () => {
  const yaml = toYaml({ ...CFG, ...FEATURED, featured_item_selector: null }, { date: '2026-10-13' });
  assert.doesNotMatch(yaml, /featured_/);
});
